const QUESTIONS = [
  "What would I receive if this release earned 1,000 MON?",
  "How many DropShares do I get for 25 MON?",
  "How do referral bonuses work here?",
];

/** Fan side: questions about shares, bonuses and revenue for one campaign. */
export function CopilotAsk({
  campaign,
  position,
  proposals,
  now,
}: {
  campaign: Campaign;
  position: Position | null;
  proposals: Proposal[];
  now: number;
}) {
  const copilot = useCopilot();
  const [question, setQuestion] = useState("");
  const [answer, setAnswer] = useState<string | null>(null);

  async function ask(q: string) {
    if (!q.trim()) return;
    setAnswer(null);
    const result = await copilot.call({
      task: "ask",
      question: q,
      campaign: toCopilotCampaign(campaign, now),
      position: toCopilotPosition(position),
      proposals: proposals.map((p) => toCopilotProposal(p, now)),
    });
    if (result && "text" in result) setAnswer(result.text);
  }

  return (
    <Panel tone="white" className="lg:col-span-2">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <Label as="h2">Ask the copilot</Label>
        <Label as="span" className="text-signal">
          KIMI · AI-assisted
        </Label>
      </div>
      {copilot.available === false ? (
        <div className="mt-3">
          <CopilotOffline />
        </div>
      ) : (
        <>
          <form
            className="mt-3 flex gap-2"
            onSubmit={(e) => {
              e.preventDefault();
              void ask(question);
            }}
          >
            <input
              aria-label="Question for the copilot"
              value={question}
              maxLength={400}
              onChange={(e) => setQuestion(e.target.value)}
              placeholder="Ask about your shares, bonuses or how revenue splits"
              className="min-w-0 flex-1 rounded-[8px] border border-ink/25 bg-white px-3 py-2.5 text-[15px] placeholder:text-ink/35 focus:border-signal"
            />
            <Button type="submit" tone="ink" busy={copilot.busy} busyLabel="Thinking…" disabled={copilot.available !== true}>
              Ask
            </Button>
          </form>
          <div className="mt-2 flex flex-wrap gap-2">
            {QUESTIONS.map((q) => (
              <button
                key={q}
                type="button"
                disabled={copilot.busy || copilot.available !== true}
                onClick={() => {
                  setQuestion(q);
                  void ask(q);
                }}
                className="min-h-11 rounded-[6px] border border-ink/20 px-2.5 py-1.5 text-left text-xs text-ink/70 transition-colors hover:border-signal hover:text-signal disabled:opacity-50"
              >
                {q}
              </button>
            ))}
          </div>
          <div aria-live="polite" className="mt-3 space-y-2">
            {copilot.error && (
              <p role="alert" className="rounded-[8px] border border-stop bg-stop-soft px-3 py-2 text-sm">
                {copilot.error}
              </p>
            )}
            {answer && <AiAssisted>{answer}</AiAssisted>}
          </div>
        </>
      )}
    </Panel>
  );
}

/** Creator side: turn a rough idea into a pitch line, a release blurb and a goal suggestion. */
export function CopilotDraftPanel({
  kind,
  creatorName,
  peers,
  onUseTagline,
  onUseGoal,
}: {
  kind: string;
  creatorName: string;
  peers: Campaign[];
  onUseTagline: (tagline: string) => void;
  onUseGoal: (goal: string) => void;
}) {
  const copilot = useCopilot();
  const [idea, setIdea] = useState("");
  const [draft, setDraft] = useState<CopilotDraft | null>(null);

  async function generate() {
    if (!idea.trim()) return;
    setDraft(null);
    const result = await copilot.call({
      task: "draft",
      idea,
      kind,
      creatorName,
      peers: peers.map((c) => ({ title: c.meta.title, kind: c.meta.kind, goalMon: mon(c.goal), raisedMon: mon(c.raised) })),
    });
    if (result && "draft" in result) setDraft(result.draft);
  }

  return (
    <div className="rounded-[8px] border border-ink/15 bg-white p-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <Label as="h3">Campaign copilot</Label>
        <Label as="span" className="text-signal">
          KIMI · AI-assisted
        </Label>
      </div>
      {copilot.available === false ? (
        <div className="mt-2">
          <CopilotOffline />
        </div>
      ) : (
        <>
          <label htmlFor="copilot-idea" className="mt-2 block text-xs text-ink/65">
            Describe the release in your own words. The copilot drafts a pitch line, a blurb and a goal you can edit.
          </label>
          <div className="mt-2 flex gap-2">
            <input
              id="copilot-idea"
              value={idea}
              maxLength={500}
              onChange={(e) => setIdea(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === "Enter") {
                  e.preventDefault();
                  void generate();
                }
              }}
              placeholder="e.g. four-track EP recorded live in one night"
              className="min-w-0 flex-1 rounded-[8px] border border-ink/25 bg-white px-3 py-2.5 text-[15px] placeholder:text-ink/35 focus:border-signal"
            />
            <Button type="button" tone="ink" busy={copilot.busy} busyLabel="Drafting…" disabled={copilot.available !== true} onClick={() => void generate()}>
              Draft
            </Button>
          </div>
          <div aria-live="polite" className="mt-3 space-y-2">
            {copilot.error && (
              <p role="alert" className="rounded-[8px] border border-stop bg-stop-soft px-3 py-2 text-sm">
                {copilot.error}
              </p>
            )}
            {draft && (
              <AiAssisted>
                <p className="font-medium">{draft.tagline}</p>
                {draft.blurb && <p className="mt-2 text-ink/75">{draft.blurb}</p>}
                {draft.suggestedGoalMon > 0 && (
                  <p className="mt-2 font-mono text-xs">
                    Suggested goal: {draft.suggestedGoalMon} MON. {draft.goalRationale}
                  </p>
                )}
                <div className="mt-3 flex flex-wrap gap-2">
                  <Button type="button" tone="ghost-ink" className="!px-3" onClick={() => onUseTagline(draft.tagline)}>
                    Use pitch line
                  </Button>
                  {draft.suggestedGoalMon > 0 && (
                    <Button
                      type="button"
                      tone="ghost-ink"
                      className="!px-3"
                      onClick={() => onUseGoal(String(draft.suggestedGoalMon))}
                    >
                      Use goal
                    </Button>
                  )}
                </div>
              </AiAssisted>
            )}
          </div>
        </>
      )}
    </div>
  );
}
